"""Admin: the login details of new accounts as an Excel file."""

import io

from openpyxl import load_workbook

from conftest import error

STUDENTS = [
    {"name": "Cruz, Ana M.", "username": "acruz", "password": "000123", "grade": "Grade 7", "section": "Rizal"},
    {"name": "Niño, Jose", "username": "jnino", "password": "x7!k2p", "grade": "", "section": ""},
]


def download(client, **data):
    return client.post("/api/users/login-details", json=data)


def test_the_file_lists_each_student_with_a_note(admin):
    response = download(admin, students=STUDENTS)
    assert response.status_code == 200 and "MyGURO login details.xlsx" in response.headers["Content-Disposition"]
    rows = list(load_workbook(io.BytesIO(response.data)).active.iter_rows(values_only=True))
    assert rows[0] == ("Name", "Username", "Password", "Grade", "Section")
    assert rows[1] == ("Cruz, Ana M.", "acruz", "000123", "Grade 7", "Rizal")  # the zeros are kept (text)
    assert rows[2][0] == "Niño, Jose" and rows[2][2] == "x7!k2p"
    assert rows[-1][0] == "Generated by MyGURO – Learning Management System"


def test_rules(admin, teacher):
    assert error(download(admin, students=[])) == "There are no login details to download."
    assert error(download(admin)) == "There are no login details to download."
    assert error(download(admin, students=["acruz"])) == "The login details are not valid."
    assert download(admin, students=[STUDENTS[0]] * 1001).status_code == 400
    assert download(teacher, students=STUDENTS).status_code == 403
